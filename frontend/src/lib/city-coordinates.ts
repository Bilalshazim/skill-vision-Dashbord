/** Normalizza come la tabella: minuscole, spazi uniformi, senza la provincia tra parentesi o dopo la virgola. */
function key(city: string): string {
  return city
    .toLowerCase()
    .replace(/\(.*?\)/g, ' ')
    .split(',')[0]
    .replace(/\s+/g, ' ')
    .trim()
}

/** [longitudine, latitudine] della città, o `null` se non è in tabella. */
export function cityCoordinates(city: string): [number, number] | null {
  return CITIES[key(city)] ?? null
}
